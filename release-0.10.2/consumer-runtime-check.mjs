import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {dirname,resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {readFileSync} from 'node:fs';
import {BetterStripe,STRIPE_CUSTOMER_PREVIEW_API_VERSION} from '@fantastic.dev/better-stripe';
import {componentsGeneric} from 'convex/server';
import {Payouts} from '@fantastic.dev/better-stripe/react';
const component=componentsGeneric().betterStripe;
const ga=new BetterStripe(component,{STRIPE_SECRET_KEY:'sk_test_runtime_contract_only'});
const preview=new BetterStripe(component,{STRIPE_SECRET_KEY:'sk_test_runtime_contract_only',stripeApiVersion:STRIPE_CUSTOMER_PREVIEW_API_VERSION});
assert.equal(ga.stripeApiVersion,'2026-09-30.endive');
assert.equal(preview.stripeApiVersion,'2026-09-30.preview');
assert.equal(typeof preview.registerRoutes,'function');
assert.throws(()=>new BetterStripe(component,{stripeApiVersion:'unsupported'}),/Unsupported Stripe API version/);
assert.equal(typeof Payouts,'function');
const req=createRequire(import.meta.url);const root=resolve(dirname(req.resolve('@fantastic.dev/better-stripe')),'../..');
assert.equal(JSON.parse(readFileSync(resolve(root,'package.json'),'utf8')).version,'0.10.2');
const {cancelsAtPeriodEnd}=await import(pathToFileURL(resolve(root,'dist/client/billing/subscriptionCancellation.js')).href);
assert.equal(cancelsAtPeriodEnd({cancel_at_period_end:false,cancel_at:2000,items:{data:[{current_period_end:2000}]}}),true);
assert.equal(cancelsAtPeriodEnd({cancel_at_period_end:false,cancel_at:null,items:{data:[{current_period_end:2000}]}}),false);
console.log(JSON.stringify({source:'official npm registry install',version:'0.10.2',gaVersion:ga.stripeApiVersion,previewVersion:preview.stripeApiVersion,instanceWebhookRoute:true,invalidVersionRejected:true,reactPayoutsExport:true,packagedPortalCancellationFix:true},null,2));
